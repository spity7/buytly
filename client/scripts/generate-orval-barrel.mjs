#!/usr/bin/env node
/**
 * After Orval `tags-split` codegen, composes all `get*` factories into one module.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const generatedRoot = path.resolve(__dirname, "../src/api/generated");

const FACTORY_RE = /export const (get[A-Za-z0-9_]+)\s*=\s*\(\)\s*=>/;

function findFactoryName(tsPath) {
  const content = fs.readFileSync(tsPath, "utf8");
  const m = content.match(FACTORY_RE);
  return m ? m[1] : null;
}

function collectTagModules() {
  const out = [];
  const entries = fs.readdirSync(generatedRoot, { withFileTypes: true });
  const dirs = entries
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();

  for (const dir of dirs) {
    const nested = path.join(generatedRoot, dir);
    const expected = path.join(nested, `${dir}.ts`);
    let tsPath = null;
    if (fs.existsSync(expected)) {
      tsPath = expected;
    } else {
      const files = fs.readdirSync(nested).filter((f) => f.endsWith(".ts"));
      if (files.length === 1) tsPath = path.join(nested, files[0]);
    }
    if (!tsPath) continue;

    const name = findFactoryName(tsPath);
    if (!name) {
      console.warn(
        `[generate-orval-barrel] skip ${tsPath}: no export const get… = () =>`,
      );
      continue;
    }

    const relDir = path.relative(generatedRoot, path.dirname(tsPath));
    const base = path.basename(tsPath, ".ts");
    const importPath = `./${relDir.replace(/\\/g, "/")}/${base}`;
    out.push({ name, importPath });
  }

  return out;
}

const modules = collectTagModules();

if (modules.length === 0) {
  console.error(
    "[generate-orval-barrel] No tag modules found under",
    generatedRoot,
  );
  process.exit(1);
}

const imports = modules
  .map((m) => `import { ${m.name} } from '${m.importPath}';`)
  .join("\n");
const spreads = modules.map((m) => `  ...${m.name}(),`).join("\n");

const banner = `/**
 * Auto-generated by scripts/generate-orval-barrel.mjs — do not edit.
 * Regenerate with "npm run gen:api".
 */
`;

const body = `${imports}

export const getBuytlyAPI = () => ({
${spreads}
});

export const buytlyApi = getBuytlyAPI();

export * from './buytly.schemas';
`;

const indexPath = path.join(generatedRoot, "index.ts");
const raw = `${banner}${body}`;

const prettier = await import("prettier");
const formatted = await prettier.format(raw, { filepath: indexPath });

fs.writeFileSync(indexPath, formatted, "utf8");
console.log(
  `[generate-orval-barrel] wrote index.ts (${modules.length} tags: ${modules
    .map((m) => m.name)
    .join(", ")})`,
);
