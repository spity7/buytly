/**
 * Asset by manifest id ("img-023"). Throws on an unknown id so a typo fails
 * the build (pages are prerendered) instead of shipping a broken image.
 * @param {string} id
 * @returns {Block57Asset}
 */
export function getAsset(id) {
  const asset = ASSETS[id];
  if (!asset) throw new Error(`Unknown Block 57 asset id "${id}"`);
  return asset;
}
